package engine

// Scale is the fixed-point scale for trust scores. No floating point is
// used anywhere in scoring, scheduling or adjudication.
const Scale int64 = 1_000_000

// BehaviorEvent is one historical behavior record. The score contribution
// is Delta*Mult in fixed-point units (scale=1e6).
type BehaviorEvent struct {
	Seq   int64 `json:"seq"`
	Delta int64 `json:"delta"`
	Mult  int64 `json:"mult"`
}

// DeviceClaim is the parsed registration declaration of one device.
type DeviceClaim struct {
	DeviceID     string          `json:"device_id"`
	TenantID     string          `json:"tenant_id"`
	Fingerprint  string          `json:"fingerprint"`
	Capabilities []string        `json:"capabilities"`
	Risk         int64           `json:"risk"`
	NeedCPU      int64           `json:"need_cpu"`
	NeedMem      int64           `json:"need_mem"`
	NeedTime     int64           `json:"need_time"`
	Events       []BehaviorEvent `json:"events"`
}

// TenantPolicy bounds trust threshold, allowed capabilities and credential
// TTL (logical time units) for one tenant.
type TenantPolicy struct {
	TenantID       string   `json:"tenant_id"`
	PolicyVersion  int64    `json:"policy_version"`
	TrustThreshold int64    `json:"trust_threshold"`
	AllowedCaps    []string `json:"allowed_caps"`
	CredTTL        int64    `json:"cred_ttl"`
}

// Params holds scheduler and concurrency parameters. Workers is the runtime
// goroutine parallelism only; it never appears in the report so that
// reports are byte-identical for any worker count.
type Params struct {
	Workers       int   `json:"-"`
	Concurrency   int   `json:"concurrency"`
	GlobalCPU     int64 `json:"global_cpu"`
	GlobalMem     int64 `json:"global_mem"`
	PerDeviceTime int64 `json:"per_device_time"`
	MaxInFlight   int   `json:"max_in_flight"`
	WaitQueueMax  int   `json:"wait_queue_max"`
}

// SampleSet is a deterministic local sample generated by the built-in
// generator. It fully describes one scenario run.
type SampleSet struct {
	Name       string         `json:"name"`
	Rounds     int            `json:"rounds"`
	Now        int64          `json:"now"`
	VerifyAt   int64          `json:"verify_at"`
	Contention int            `json:"contention,omitempty"`
	Params     Params         `json:"params"`
	Policies   []TenantPolicy `json:"policies"`
	Claims     []DeviceClaim  `json:"claims"`
	Claims2    []DeviceClaim  `json:"claims2,omitempty"`
}
